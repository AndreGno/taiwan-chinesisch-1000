final_map = {}
final_unresolved = []

for c, v in resolved.items():
    if v["unanimous"]:
        final_map[c] = v["correct"]
    elif c in manual_by_char:
        final_map[c] = manual_by_char[c]
    else:
        final_unresolved.append(f"U+{ord(c):04X}")

for u in unresolved:
    c = u["char"]
    if c in manual_by_char:
        final_map[c] = manual_by_char[c]
    else:
        final_unresolved.append(u["codepoint"])

print(f"\nEndgueltige Tabelle: {len(final_map)} Zeichen")
print(f"Weiterhin ungeklaert: {len(final_unresolved)} -> {final_unresolved}")

with open(HERE / "final_char_map.json", "w", encoding="utf-8") as f:
    json.dump({f"U+{ord(c):04X}": v for c, v in final_map.items()}, f, ensure_ascii=False, indent=2)

